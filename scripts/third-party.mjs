// Writes THIRD_PARTY_NOTICES.md: every production dependency of the shipped packages with its license (NFA-16).
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const seen = new Map();
// Packages whose package.json carries no license field; verified by reading their LICENSE file.
const LICENSE_FILE_OVERRIDES = { khroma: "MIT" };

function readPkg(dir) {
  try {
    return JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  } catch {
    return null;
  }
}
function resolveDep(name, from) {
  let dir = from;
  for (;;) {
    const p = path.join(dir, "node_modules", name);
    if (fs.existsSync(path.join(p, "package.json"))) return p;
    const up = path.dirname(dir);
    if (up === dir) return null;
    dir = up;
  }
}
function walk(pkgDir, depth = 0) {
  const pkg = readPkg(pkgDir);
  if (!pkg) return;
  for (const name of Object.keys(pkg.dependencies ?? {})) {
    if (name.startsWith("@pi-browser/") || name === "pi-browser-bridge") continue;
    const dir = resolveDep(name, pkgDir) ?? resolveDep(name, root);
    if (!dir) continue;
    const p = readPkg(dir);
    const key = `${p.name}@${p.version}`;
    if (seen.has(key)) continue;
    const lic = typeof p.license === "string" ? p.license : p.license?.type ?? (p.licenses?.map((l) => l.type).join(" OR ") ?? "UNKNOWN");
    seen.set(key, { name: p.name, version: p.version, license: (lic === "UNKNOWN" && LICENSE_FILE_OVERRIDES[p.name]) || lic, homepage: p.homepage ?? p.repository?.url ?? "" });
    walk(dir, depth + 1);
  }
}
for (const ws of ["extension", "packages/shared", "packages/bridge", "packages/host"]) walk(path.join(root, ws));
const rows = [...seen.values()].sort((a, b) => a.name.localeCompare(b.name));
const out = [
  "# Third-party notices",
  "",
  "This project's own code is MIT licensed (see LICENSE). It contains no code, text, icons or fonts from any other browser extension.",
  "The following open-source packages are used by the shipped packages (production dependencies, transitive included):",
  "",
  "| Package | Version | License |",
  "|---|---|---|",
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} |`),
  "",
  `Generated by scripts/third-party.mjs (${rows.length} packages).`,
  "",
];
fs.writeFileSync(path.join(root, "THIRD_PARTY_NOTICES.md"), out.join("\n"));
const bad = rows.filter((r) => /GPL|AGPL|SSPL|UNKNOWN|CC-BY-NC/i.test(r.license) && !/LGPL/i.test(r.license));
console.log(`${rows.length} packages; problematic licenses: ${bad.length ? bad.map((b) => `${b.name} (${b.license})`).join(", ") : "none"}`);
